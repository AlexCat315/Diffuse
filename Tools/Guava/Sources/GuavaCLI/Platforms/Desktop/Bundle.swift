import Foundation

struct DesktopPackage {
    struct Artifact {
        let directory: URL
        let executable: URL
    }
    let project: AppProject
    let platform: AppPlatform

    func assemble(binaries: URL, configuration: BuildConfiguration, output: URL?) throws -> Artifact {
        let product = project.configuration.targets.desktopProduct
        let isMac = platform == .mac
        let destination = output ?? project.buildDirectory.appendingPathComponent("\(platform.rawValue)/\(configuration.rawValue)/\(product)\(isMac ? ".app" : "")")
        if isMac, destination.pathExtension != "app" { throw ToolError.invalid("macOS --output must name an .app directory") }
        // Custom outputs must not replace a project, sources, or arbitrary existing directory.
        if FileManager.default.fileExists(atPath: destination.path) {
            let marker = destination.appendingPathComponent(".guava-artifact")
            guard FileManager.default.fileExists(atPath: marker.path) else {
                throw ToolError.invalid("Refusing to replace an unowned output: \(destination.path)")
            }
        }
        try Files.reset(destination)
        try Files.text("Generated by guava build\n", to: destination.appendingPathComponent(".guava-artifact"))
        let executableDirectory = isMac ? destination.appendingPathComponent("Contents/MacOS") : destination
        let resourceDirectory = isMac ? destination.appendingPathComponent("Contents/Resources") : destination
        let filename = product + (platform == .win ? ".exe" : "")
        let executable = executableDirectory.appendingPathComponent(filename)
        try Files.copy(binaries.appendingPathComponent(filename), to: executable)
        for child in try Files.children(binaries) {
            if ["bundle", "resources"].contains(child.pathExtension) {
                try Files.copy(child, to: resourceDirectory.appendingPathComponent(child.lastPathComponent))
            } else if ["dylib", "dll", "so"].contains(child.pathExtension) || child.lastPathComponent.contains(".so.") {
                try Files.copy(child, to: executableDirectory.appendingPathComponent(child.lastPathComponent))
            }
        }
        if isMac {
            let identity = project.configuration.application
            let plist: [String: Any] = ["CFBundleIdentifier": identity.id, "CFBundleDisplayName": identity.name,
                "CFBundleName": identity.name, "CFBundleExecutable": product, "CFBundlePackageType": "APPL",
                "CFBundleVersion": "1", "CFBundleShortVersionString": "0.1.0", "NSHighResolutionCapable": true,
                "NSPrincipalClass": "NSApplication", "LSMinimumSystemVersion": "13.0"]
            let data = try PropertyListSerialization.data(fromPropertyList: plist, format: .xml, options: 0)
            try data.write(to: destination.appendingPathComponent("Contents/Info.plist"))
        }
        return Artifact(directory: destination, executable: executable)
    }
}

//! Destruction vocabulary: authored settings, pre-fracture assets, command and
//! event payloads, and the internal runtime bookkeeping types.
//!
//! Ported from `Engine/Sources/SceneRuntime/Physics/Destruction.swift`.
//!
//! Every `init` clamps exactly where Swift's does. Swift's `max(0, value)` is
//! `value >= 0 ? value : 0`, so a NaN becomes `0`; Rust's `f32::max` returns the
//! non-NaN operand, which is the same result. The tests below pin that down
//! rather than leaving it as an assumption.
//!
//! Maps keyed by `EntityID` or `String` are `BTreeMap`, not `HashMap`: Swift
//! `Dictionary` order is random per process, and these states feed hashes and the
//! debug frame (MIGRATION.md §5.2).

use std::collections::{BTreeMap, BTreeSet};

